const dictionaries: Record<Language, Record<TranslationKey, string>> = { zh, en, de };
const nextLanguage: Record<Language, Language> = { zh: 'en', en: 'de', de: 'zh' };
const languageShort: Record<Language, string> = { zh: '中', en: 'EN', de: 'DE' };
let language: Language = loadLanguage();
const listeners = new Set<() => void>();

export function isLanguage(value: unknown): value is Language { return LANGUAGES.includes(value as Language); }
export function loadLanguage(storage?: Pick<Storage, 'getItem'>): Language {
  try { const stored=(storage ?? (typeof window === 'undefined' ? undefined : window.localStorage))?.getItem(LANGUAGE_STORAGE_KEY);if(isLanguage(stored))return stored; } catch { /* Use the default language when storage is unavailable. */ }
  return DEFAULT_LANGUAGE;
}
export function getLanguage(): Language { return language; }
export function t(key: TranslationKey, values: Record<string, string | number> = {}): string {
  return dictionaries[language][key].replace(/\{(\w+)\}/g,(_,name: string)=>String(values[name]??`{${name}}`));
}
export function setLanguage(next: Language): void {
  if(next===language)return;
  language=next;
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY,next); } catch { /* Keep the session preference. */ }
  for(const listener of listeners)listener();
}
export function onLanguageChange(listener: () => void): () => void { listeners.add(listener);return ()=>listeners.delete(listener); }
export function translateDocument(root: ParentNode = document): void {
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach(element=>{element.innerHTML=t(element.dataset.i18n as TranslationKey);});
  root.querySelectorAll<HTMLElement>('[data-i18n-aria-label]').forEach(element=>element.setAttribute('aria-label',t(element.dataset.i18nAriaLabel as TranslationKey)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach(element=>element.title=t(element.dataset.i18nTitle as TranslationKey));
  document.documentElement.lang=language==='zh'?'zh-CN':language;
  document.title=t('document.title');
}
export function setupLanguageSwitch(button: HTMLButtonElement): void {
  const apply=()=>{
    const next=nextLanguage[language];
    button.textContent=languageShort[next];
    button.setAttribute('aria-label',t('language.switch'));
    button.title=t('language.switch');
  };
  button.addEventListener('click',()=>setLanguage(nextLanguage[language]));
  onLanguageChange(apply);apply();
}
